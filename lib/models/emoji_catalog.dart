/// Кодирование стикеров в тексте сообщения (бекенд хранит обычный text).
abstract final class StickerCodec {
  static final RegExp pattern = RegExp(r'^\[\[sticker:(.+)\]\]$');

  static String encode(String emoji) => '[[sticker:$emoji]]';

  static String? decode(String text) {
    final m = pattern.firstMatch(text.trim());
    return m?.group(1);
  }

  static bool isSticker(String text) => pattern.hasMatch(text.trim());
}

